export function glyphAlpha(ch: string, scale = 1): { w: number; h: number; alpha: Uint8Array } {
  const key = ch === " " ? " " : ch.toUpperCase();
  const bits = BITS[key] ?? BITS["?"];
  const sw = 5 * scale;
  const sh = 7 * scale;
  const alpha = new Uint8Array(sw * sh);
  if (!bits) return { w: sw, h: sh, alpha };
  for (let y = 0; y < 7; y += 1) {
    for (let x = 0; x < 5; x += 1) {
      if (bits[y * 5 + x] !== "1") continue;
      for (let dy = 0; dy < scale; dy += 1) {
        for (let dx = 0; dx < scale; dx += 1) {
          alpha[(y * scale + dy) * sw + x * scale + dx] = 255;
        }
      }
    }
  }
  return { w: sw, h: sh, alpha };
}

/** Adds a one-pixel rim so the title face reads heavier. */
export function thicken(alpha: Uint8Array, w: number, h: number): Uint8Array {
  const out = new Uint8Array(alpha);
  for (let y = 0; y < h; y += 1) {
    for (let x = 0; x < w; x += 1) {
      if (!alpha[y * w + x]) continue;
      if (x + 1 < w) out[y * w + x + 1] = 255;
      if (y + 1 < h) out[(y + 1) * w + x] = 255;
    }
  }
  return out;
}

