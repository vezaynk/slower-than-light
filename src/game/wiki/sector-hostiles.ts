/**
 * Hostile encounters per sector type: which fight events a sector's hostile beacons draw, and the ship each one fields.
 * enemy-gen.ts turns this into the pool and the weights of a sector's random ("pool") fights.
 *
 * Two kinds of source, best first:
 *
 * 1. DOCUMENTED event lists. Wiki "Sectors", Civilian (Starting) Sector: "4-6 [[Template:EventList HOSTILE_CIVILIAN|
 *    hostile_civilian]] events" and "2 [[Template:EventList HOSTILE1|hostile1]] / [[Template:EventList OVERRIDE_HOSTILE1|
 *    override_hostile1]] events". Civilian Sector: "6-8 hostile encounters <!-- 4-6 from "HOSTILE_CIVILIAN" eventList and
 *    2-2 from "HOSTILE1" eventList, which comes after "QUESTS" -->". The two templates print every entry.
 *    Sectors: "'override_...' eventlists are used when Advanced Edition Content is enabled". This game has the Advanced
 *    Edition races (Lanius) and systems, so OVERRIDE_HOSTILE1 is the list used.
 *    Sectors: the order of entries "doesn't affect the likelihood of them being chosen over the other ones in the same
 *    eventList". So each entry weighs (draws from that list) / (entries in that list); 4-6 draws count as 5. INFERRED: the
 *    midpoint, and "unique" entries (once per sector) are not discounted.
 *
 * 2. DERIVED from event pages, for every other sector. The dump has no eventList template for any other sector, and the
 *    Sectors page names none ("@TO-DO: The beacons listing on this page should be updated to reflect the actual
 *    evenLists"); it prints only the count ("6-8 hostile encounters", "5-7 nebula hostile encounters", ...) and links each
 *    sector's event category. Category pages carry no member list; membership is each event page's {{Locations|...}}
 *    line. INFERRED membership rule: an event counts as a hostile encounter of a sector when its {{Locations}} names the
 *    sector, its long-range-scanner flag shows a ship ("LRSmap=ship...", or a plasma storm that hides it), and the page
 *    links a fight with a ship ("Fight a [[Rebel Ships|Rebel ship]]", "[[Enemy Ships|Pirate ship]]", ...).
 *    Left out by hand, with the reason:
 *    - "Slaver (friendly)": a trade ("Buy one slave ..."); the fight is only the "Attack the slaver scum" choice.
 *    - "Deactivated Auto-ship": "it appears to be de-activated"; the fight is one outcome of salvaging it.
 *    - "Legendary thief KazaaakplethKilik": Sectors, Mantis Homeworlds, places it by name ("1 Legendary thief ... event").
 *    - "Slug Home Nebula surrender": its page says the sector definition places it once
 *      ('<event name="NEBULA_SLUG_FIGHT_UNLOCK" min="1" max="1"/>').
 *    Each event counts once. INFERRED: the dump does not say how many lists an event sits in or how often.
 *
 * The ship of each event is the first fight its page links, read the way enemy-gen.ts requestFor reads a fight tier.
 */

