/** Hangar sheet lines name systems in words ("Oxygen", "Drone Control"). */
const NAME_ICONS: [RegExp, IconName][] = [
  [/shield/, "shields"],
  [/engine/, "engines"],
  [/oxygen|^o2$/, "oxygen"],
  [/med/, "medbay"],
  [/drone/, "swarm"],
  [/weapon/, "weapons"],
  [/pilot/, "pilot"],
  [/sensor/, "sensors"],
  [/door/, "doors"],
  [/clon/, "cradle"],
  [/hack/, "spike"],
  [/mind/, "leash"],
  [/cloak/, "veil"],
  [/teleport/, "sling"],
  [/battery/, "cell"],
  [/flak/, "flak"],
  [/artillery|beam/, "lance"],
];

export function iconForName(name: string): IconName | null {
  const key = name.toLowerCase();
  return NAME_ICONS.find(([re]) => re.test(key))?.[1] ?? null;
}
